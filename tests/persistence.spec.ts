import { expect, test } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import fixture from './fixtures/catalog.json' with { type: 'json' };
import { selectGenre } from './ui';

test('saved plans and portable backups preserve edits, while incompatible imports preserve existing work', async ({ page, browser }) => {
  await page.route('**/catalog.json', route => route.fulfill({ json: fixture }));
  await page.goto('/'); await selectGenre(page, 'House');
  await page.getByLabel('Performance context').fill('Warm-up');
  await page.getByLabel('Emphasis for House').fill('3');
  await page.getByLabel('Emphasis for House').press('Tab');
  await page.getByRole('button', { name: 'Generate set plan', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Save plan', exact: true })).toBeVisible();
  await page.getByLabel('Notes for track 1').fill('My cue, "listen"\nA second line');
  await page.getByLabel('Notes for track 1').press('Tab');
  await page.getByLabel('Lock inclusion for track 1').check();
  await page.getByLabel('Pin position for track 1').fill('1');
  await page.getByLabel('Pin position for track 1').press('Tab');
  await page.getByLabel('Play time for track 1 (seconds)').fill('180');
  await page.getByLabel('Play time for track 1 (seconds)').press('Tab');
  await page.getByText('Edit energy arc', { exact: true }).click();
  await page.getByLabel('End of Anchor (minutes)').fill('16');
  await page.getByLabel('End of Anchor (minutes)').press('Tab');
  const row = page.getByRole('table', { name: 'Tracklist' }).getByRole('row').nth(1);
  await row.getByText('Correct estimate').click();
  await page.getByLabel('Energy estimate for track 1').fill('7');
  await page.getByLabel('Energy basis for track 1').fill('Personal listening assessment');
  await page.getByRole('button', { name: 'Apply energy for track 1', exact: true }).click();
  const library = `<DJ_PLAYLISTS><COLLECTION><TRACK TrackID="1" Name="Fixture groove" Artist="Test artist" Mix="Original Mix" Location="file://localhost/Music/original.mp3" /></COLLECTION></DJ_PLAYLISTS>`;
  await page.getByLabel('Import Rekordbox XML').setInputFiles({ name: 'library.xml', mimeType: 'application/xml', buffer: Buffer.from(library) });
  await page.getByLabel('Plan name').fill('Friday warm-up');
  await page.getByRole('button', { name: 'Save plan', exact: true }).click();
  await expect(page.getByText('Saved locally.', { exact: true })).toBeVisible();
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Back up plan', exact: true }).click();
  const download = await downloadEvent;
  const backup = await readFile((await download.path())!);
  const content = JSON.parse(backup.toString());
  expect(content.version).toBe(1);
  await page.reload();
  await page.getByLabel('Saved plans').selectOption({ label: 'Friday warm-up' });
  await page.getByRole('button', { name: 'Open saved plan', exact: true }).click();
  await expect(page.getByLabel('Notes for track 1')).toHaveValue('My cue, "listen"\nA second line');
  await expect(page.getByLabel('Pin position for track 1')).toHaveValue('1');
  await expect(page.getByLabel('Lock inclusion for track 1')).toBeChecked();
  await expect(page.getByLabel('Play time for track 1 (seconds)')).toHaveValue('180');
  await expect(page.getByLabel('End of Anchor (minutes)')).toHaveValue('16');
  await expect(row).toContainText('Personal listening assessment');
  await expect(page.getByLabel('Performance context')).toHaveValue('Warm-up');
  await expect(page.getByLabel('Emphasis for House')).toHaveValue('3');
  await expect(page.getByLabel('Library import status')).toContainText('1 library entries');

  const context = await browser.newContext();
  const fresh = await context.newPage();
  await fresh.goto('/');
  await fresh.getByLabel('Import plan backup').setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: backup });
  await expect(fresh.getByLabel('Notes for track 1')).toHaveValue('My cue, "listen"\nA second line');
  await expect(fresh.getByLabel('End of Anchor (minutes)')).toHaveValue('16');
  await expect(fresh.getByLabel('Library import status')).toContainText('1 library entries');
  await fresh.getByLabel('Import plan backup').setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ ...content, version: 99 })) });
  await expect(fresh.getByRole('alert')).toContainText('Unsupported backup version');
  await expect(fresh.getByLabel('Notes for track 1')).toHaveValue('My cue, "listen"\nA second line');
  await context.close();
});

test('storage failures are exposed while the current plan remains available', async ({ page }) => {
  await page.route('**/catalog.json', route => route.fulfill({ json: fixture }));
  await page.addInitScript(() => { Storage.prototype.setItem = () => { throw new DOMException('Storage is full', 'QuotaExceededError'); }; });
  await page.goto('/'); await selectGenre(page, 'House');
  await page.getByRole('button', { name: 'Generate set plan', exact: true }).click();
  await page.getByRole('button', { name: 'Save plan', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Saving failed');
  await expect(page.getByText('Saved locally.', { exact: true })).toHaveCount(0);
  await expect(page.getByRole('table', { name: 'Tracklist' })).toContainText('Fixture groove');
});
